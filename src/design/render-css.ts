import {
  colorTokens, elevationTokens, motionTokens, radiusTokens, touchTarget, typeTokens,
  type ColorToken, type ThemeName,
} from './tokens';

const names = Object.keys(colorTokens) as ColorToken[];
const vars = (theme: ThemeName, indent: string) =>
  names.map((name) => `${indent}--ds-${name}: ${colorTokens[name][theme]};`).join('\n');

/** Renders src/design/tokens.css from tokens.ts. Deterministic, so CI can diff it. */
export function renderTokensCss(): string {
  const theme = names.map((name) => `  --color-${name}: var(--ds-${name});`).join('\n');
  return `/* GENERATED by scripts/build-design-tokens.ts from src/design/tokens.ts. Do not edit. */
:root {
  color-scheme: light;
${vars('light', '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${vars('dark', '    ')}
  }
}

:root[data-theme="dark"] {
  color-scheme: dark;
${vars('dark', '  ')}
}

@theme inline {
${theme}
  --radius-control: ${radiusTokens.control}px;
  --radius-card: ${radiusTokens.card}px;
  --radius-pill: ${radiusTokens.pill}px;
  --font-ui: ${typeTokens.family};
  --shadow-card: ${elevationTokens.card};
  --shadow-sheet: ${elevationTokens.sheet};
  --spacing-touch: ${touchTarget}px;
}

:root {
  --ds-motion-fast: ${motionTokens.fast}ms;
  --ds-motion-base: ${motionTokens.base}ms;
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --ds-motion-fast: 0ms;
    --ds-motion-base: 0ms;
  }
}
`;
}
